// adoptedTool is one tool inferred from tracked state or the personal
// manifest. Methods lists every method candidate in declaration order; an
// empty Methods slice means the source did not record enough to declare one.
type adoptedTool struct {
	Name    string
	Tags    []string
	Methods []adoptedMethod
	Note    string
}

type adoptedMethod struct {
	Kind   string
	Label  string
	Config map[string]any
}

// initAdoptOptions carries the resolved flag values for adoption mode.
type initAdoptOptions struct {
	Output       string
	FromState    string
	FromManifest string
	DryRun       bool
}

// runInitAdopt generates or merges schema.toml from existing installation
// knowledge instead of asking the user to retype tool names.
func runInitAdopt(opts initAdoptOptions) error {
	path := opts.Output
	if path == "" {
		path = "schema.toml"
	}

	var (
		tools  []adoptedTool
		source string
		err    error
	)
	switch {
	case opts.FromState != "":
		tools, source, err = adoptFromState(opts.FromState)
	case opts.FromManifest != "":
		tools, source, err = adoptFromManifest(opts.FromManifest)
	}
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		return exitWithCode(2)
	}
	if len(tools) == 0 {
		fmt.Fprintf(os.Stderr, "error: %s contains no tools to adopt\n", source)
		return exitWithCode(1)
	}

	existing, readErr := os.ReadFile(path) // #nosec G304 -- the target is an explicit project path chosen by the user.
	exists := readErr == nil
	if readErr != nil && !os.IsNotExist(readErr) {
		fmt.Fprintf(os.Stderr, "error: cannot read %s: %v\n", path, readErr)
		return exitWithCode(1)
	}

	declared := map[string]bool{}
	content := ""
	if exists {
		parsed, parseErr := config.ParseProjectSchema(path, map[string]string{})
		if parseErr != nil {
			fmt.Fprintf(os.Stderr, "error: %s exists but is not a valid schema: %v\n", path, parseErr)
			return exitWithCode(2)
		}
		for name := range parsed.Tools {
			declared[name] = true
		}
		content = string(existing)
	}

	var blocks []string
	var adopted, skipped []string
	for _, tool := range tools {
		if declared[tool.Name] {
			skipped = append(skipped, tool.Name)
			continue
		}
		blocks = append(blocks, renderAdoptedTool(tool, source))
		adopted = append(adopted, tool.Name)
	}

	if len(blocks) == 0 {
		fmt.Fprintf(os.Stderr, "%s already declares every tool from %s; nothing to do\n", path, source)
		return nil
	}

	result := content
	if !exists {
		result = initAdoptHeader(filepath.Base(path), source)
	}
	if result != "" && !strings.HasSuffix(result, "\n") {
		result += "\n"
	}
	for _, block := range blocks {
		result += "\n" + block
	}

	if opts.DryRun {
		_, _ = fmt.Fprint(os.Stdout, result)
		fmt.Fprintf(os.Stderr, "would %s %s with %d adopted tools", mergeVerb(exists), path, len(adopted))
		if len(skipped) > 0 {
			fmt.Fprintf(os.Stderr, " (%d already declared)", len(skipped))
		}
		fmt.Fprintln(os.Stderr)
		return nil
	}

	dir := filepath.Dir(path)
	if dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil { // #nosec G301 -- project schema directories are shared with collaborators.
			fmt.Fprintf(os.Stderr, "error: cannot create directory %s: %v\n", dir, err)
			return exitWithCode(1)
		}
	}
	if err := os.WriteFile(path, []byte(result), 0o644); err != nil { // #nosec G306 G703 -- schema.toml is the explicit user-selected output path and is intended to be shared and committed.
		fmt.Fprintf(os.Stderr, "error: cannot write %s: %v\n", path, err)
		return exitWithCode(1)
	}

	c := newCLIStyle(os.Stdout)
	verb := "created"
	if exists {
		verb = "updated"
	}
	msg := fmt.Sprintf("✓ %s %s with %d tools from %s", path, verb, len(adopted), source)
	_, _ = fmt.Fprintln(c.w, c.green(msg))
	if len(skipped) > 0 {
		fmt.Fprintf(os.Stderr, "  kept %d already-declared tools: %s\n", len(skipped), strings.Join(skipped, ", "))
	}
	fmt.Fprintln(os.Stderr, "Next: review the TODO comments, then run 'depengine validate'.")
	return nil
}

func mergeVerb(exists bool) string {
	if exists {
		return "update"
	}
	return "create"
}

// initAdoptHeader is the file preamble used when adoption creates a new schema.
func initAdoptHeader(basename, source string) string {
	return fmt.Sprintf(`# %s — depengine project configuration
# Generated by 'depengine init' from %s
# See: https://github.com/Khorea1/depengine
#
# Review TODO comments before committing: adoption records what was installed,
# not necessarily the minimum method set the project should declare.
#
# Commit this file so everyone on the project gets the same declared tool set:
#   git add %s depengine.lock && git commit
# Personal installation knowledge goes in ~/.config/depengine/manifest.toml.

schema_version = 1
`, basename, source, basename)
}

// adoptFromState reads tracked installation state. A missing state file is an
// error: there is nothing to adopt.
func adoptFromState(spec string) ([]adoptedTool, string, error) {
	path := spec
	if spec == "auto" {
		path = state.DefaultPath()
	}
	if path == "" {
		return nil, "", fmt.Errorf("cannot determine the state file path; set XDG_STATE_HOME or pass --from-state=<path>")
	}
	if _, err := os.Stat(path); err != nil {
		return nil, "", fmt.Errorf("state file %s: %w", path, err)
	}
	st, err := state.LoadFrom(path)
	if err != nil {
		return nil, "", fmt.Errorf("load state %s: %w", path, err)
	}

	names := make([]string, 0, len(st.Tools))
	for name := range st.Tools {
		names = append(names, name)
	}
	sort.Strings(names)

	tools := make([]adoptedTool, 0, len(names))
	for _, name := range names {
		ts := st.Tools[name]
		kind := ts.MethodKind
		label := ts.Method
		if kind == "" {
			kind = ts.Method
		}
		tool := adoptedTool{Name: name}
		if kind == "" {
			tool.Note = fmt.Sprintf("state recorded no method for %s; declare its install method manually", name)
			tools = append(tools, tool)
			continue
		}
		if label == "" || label == kind {
			label = kind
		}
		tool.Methods = []adoptedMethod{{Kind: kind, Label: label, Config: ts.Config}}
		if ts.Version != "" {
			tool.Note = fmt.Sprintf("installed version was %s; add a version pin if the project needs one", ts.Version)
		}
		if ts.Provider != "" && ts.Provider != kind {
			tool.Note = strings.TrimSpace(strings.Join([]string{tool.Note, fmt.Sprintf("provider was %s", ts.Provider)}, "; "))
		}
		tools = append(tools, tool)
	}
	return tools, "state (" + path + ")", nil
}

// adoptFromManifest converts manifest packages into project schema entries.
// Manifest entries are already method declarations, so the conversion is
// mostly structural.
func adoptFromManifest(spec string) ([]adoptedTool, string, error) {
	path := spec
	if spec == "auto" {
		path = config.DefaultManifestPath()
	}
	if path == "" {
		return nil, "", fmt.Errorf("cannot determine the manifest path; pass --from-manifest=<path>")
	}
	manifest, err := config.ParseManifest(path, nil)
	if err != nil {
		return nil, "", fmt.Errorf("load manifest %s: %w", path, err)
	}

	names := make([]string, 0, len(manifest.Tools))
	for name := range manifest.Tools {
		names = append(names, name)
	}
	sort.Strings(names)

	tools := make([]adoptedTool, 0, len(names))
	for _, name := range names {
		entry := manifest.Tools[name]
		tool := adoptedTool{Name: name, Tags: entry.Tags}
		for _, method := range entry.Methods {
			if method == nil {
				continue
			}
			label := method.Label
			if label == "" {
				label = method.Kind
			}
			tool.Methods = append(tool.Methods, adoptedMethod{Kind: method.Kind, Label: label, Config: method.Config})
		}
		tool.Methods = mergeAdoptedMethods(tool.Methods)
		if len(tool.Methods) == 0 {
			tool.Note = "manifest declared no method; declare one manually"
		}
		tools = append(tools, tool)
	}
	return tools, "manifest (" + path + ")", nil
}

// labelImpliesKind reports whether the subtable label already selects the
// method kind. TOML rejects a `kind` override under a non-custom label, and
// aliases such as "yay" (aur) already name their kind.
func labelImpliesKind(label, kind string) bool {
	if label == kind {
		return true
	}
	for _, contract := range methodkind.Contracts {
		if contract.Kind != kind {
			continue
		}
		for _, alias := range contract.Aliases {
			if alias == label {
				return true
			}
		}
	}
	return false
}

// mergeAdoptedMethods collapses candidates that share a kind and label. The
// parser expands shorthands such as `native = true` into an inferred native
// candidate plus an explicit one, and both must become a single table.
func mergeAdoptedMethods(methods []adoptedMethod) []adoptedMethod {
	merged := make([]adoptedMethod, 0, len(methods))
	index := map[string]int{}
	for _, method := range methods {
		key := method.Kind + "\x00" + method.Label
		position, seen := index[key]
		if !seen {
			index[key] = len(merged)
			merged = append(merged, adoptedMethod{Kind: method.Kind, Label: method.Label, Config: map[string]any{}})
			position = len(merged) - 1
		}
		target := merged[position]
		if target.Config == nil {
			target.Config = map[string]any{}
		}
		for configKey, value := range method.Config {
			if current, ok := target.Config[configKey]; ok && !isEmptyAdoptedValue(current) {
				continue
			}
			target.Config[configKey] = value
		}
		merged[position] = target
	}
	return merged
}

func isEmptyAdoptedValue(value any) bool {
	text, ok := value.(string)
	return ok && text == ""
}

// renderAdoptedTool renders one tool as TOML. Method config keys that cannot be
// represented become TODO comments instead of being dropped silently.
func renderAdoptedTool(tool adoptedTool, source string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# adopted from %s\n", source)
	if tool.Note != "" {
		fmt.Fprintf(&b, "# TODO: %s\n", tool.Note)
	}
	if len(tool.Methods) == 0 {
		fmt.Fprintf(&b, "# [tools.%s]  # TODO: no usable method recorded\n", tomlKeyPart(tool.Name))
		return b.String()
	}

	if len(tool.Tags) > 0 {
		fmt.Fprintf(&b, "[tools.%s]\ntags = %s\n", tomlKeyPart(tool.Name), tomlStringList(tool.Tags))
	}
	for _, method := range tool.Methods {
		// Alias labels ("yay" for aur) dispatch through the canonical kind,
		// so the adopted table uses the kind instead of the alias.
		label := method.Label
		if labelImpliesKind(label, method.Kind) {
			label = method.Kind
		}
		fmt.Fprintf(&b, "[tools.%s.%s]\n", tomlKeyPart(tool.Name), tomlKeyPart(label))
		if label != method.Kind {
			fmt.Fprintf(&b, "kind = %q\n", method.Kind)
		}
		keys := make([]string, 0, len(method.Config))
		for key := range method.Config {
			if strings.HasPrefix(key, "_") {
				// Internal state bookkeeping, not a schema field.
				continue
			}
			keys = append(keys, key)
		}
		sort.Strings(keys)
		for _, key := range keys {
			value, ok := tomlValue(method.Config[key])
			if !ok {
				fmt.Fprintf(&b, "# TODO: field %q could not be rendered automatically; declare it manually\n", key)
				continue
			}
			if value == `""` {
				// Empty strings mean "use the default" in every method config;
				// omitting them is the readable spelling.
				continue
			}
			fmt.Fprintf(&b, "%s = %s\n", tomlKeyPart(key), value)
		}
	}
	return b.String()
}

// tomlKeyPart quotes a table/key component only when TOML requires it.
func tomlKeyPart(key string) string {
	if isTOMLBareKey(key) {
		return key
	}
	return strconv.Quote(key)
}

func isTOMLBareKey(key string) bool {
	if key == "" {
		return false
	}
	for _, r := range key {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '-', r == '_':
		default:
			return false
		}
	}
	return true
}

func tomlStringList(values []string) string {
	quoted := make([]string, len(values))
	for i, value := range values {
		quoted[i] = strconv.Quote(value)
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

// tomlValue renders the scalar and container types state and manifests use.
func tomlValue(value any) (string, bool) {
	switch typed := value.(type) {
	case string:
		return strconv.Quote(typed), true
	case bool:
		return strconv.FormatBool(typed), true
	case int:
		return strconv.Itoa(typed), true
	case int64:
		return strconv.FormatInt(typed, 10), true
	case float64:
		if typed == float64(int64(typed)) {
			return strconv.FormatInt(int64(typed), 10), true
		}
		return strconv.FormatFloat(typed, 'g', -1, 64), true
	case []string:
		return tomlStringList(typed), true
	case []any:
		parts := make([]string, 0, len(typed))
		for _, item := range typed {
			rendered, ok := tomlValue(item)
			if !ok {
				return "", false
			}
			parts = append(parts, rendered)
		}
		return "[" + strings.Join(parts, ", ") + "]", true
	case map[string]any:
		keys := make([]string, 0, len(typed))
		for key := range typed {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		parts := make([]string, 0, len(keys))
		for _, key := range keys {
			rendered, ok := tomlValue(typed[key])
			if !ok {
				return "", false
			}
			parts = append(parts, tomlKeyPart(key)+" = "+rendered)
		}
		return "{ " + strings.Join(parts, ", ") + " }", true
	default:
		return "", false
	}
}
